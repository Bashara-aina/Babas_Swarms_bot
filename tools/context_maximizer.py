# ── Token counter (tiktoken-style approximation) ──────────────────
def count_tokens(text: str) -> int:
    """Approximate token count. Accurate within ~5% for English+code mix."""
    return max(1, len(text) // 4)

# ── Heuristic pruning (no model needed) ───────────────────────────
def prune_text(text: str) -> tuple[str, int]:
    """
    Remove obvious waste: duplicates, boilerplate, verbose sections.
    Returns (pruned_text, chars_removed).
    """
    original_len = len(text)
    lines = text.split('\n')
    pruned = []
    seen_lines = set()

    for line in lines:
        stripped = line.strip()
        # Skip exact duplicate lines (keep first occurrence)
        if stripped in seen_lines and len(stripped) > 20:
            continue
        seen_lines.add(stripped)
        # Skip obvious boilerplate license headers
        if re.match(r'^\s*\*+\s*Copyright\s+\d{4}', stripped):
            continue
        if re.match(r'^\s*SPDX-License-Identifier:', stripped):
            continue
        # Skip auto-generated markers
        if re.search(r'Generated by|autogenerated|auto-generated', stripped, re.I):
            continue
        pruned.append(line)

    result = '\n'.join(pruned)
    return result, original_len - len(result)

# ── Context budget tracker ────────────────────────────────────────
class ContextBudget:
    TOTAL = 204800
    SYSTEM_RESERVED = 6000
    OUTPUT_RESERVED = 8192
    SAFETY_BUFFER = 2048
    AVAILABLE = TOTAL - SYSTEM_RESERVED - OUTPUT_RESERVED - SAFETY_BUFFER

    def __init__(self):
        self.used = 0
        self.log = []
        self.pruned_chars = 0

    def add(self, label: str, content: str, compress_ratio: float | None = None):
        pruned_content, chars_removed = prune_text(content)
        self.pruned_chars += chars_removed

        if compress_ratio and compress_ratio < 1.0 and len(pruned_content) > 5000:
            keep_start = int(len(pruned_content) * 0.4)
            keep_end = int(len(pruned_content) * 0.4)
            target = int(len(pruned_content) * compress_ratio)
            if keep_start + keep_end < target:
                pruned_content = (pruned_content[:keep_start] +
                                  f'\n\n[... compressed {int((1-compress_ratio)*100)}% ...]\n\n' +
                                  pruned_content[-keep_end:])
            tokens = count_tokens(pruned_content)
            self.log.append(f"{label}: {count_tokens(content)}→{tokens} tokens (pruned {chars_removed} chars)")
        else:
            tokens = count_tokens(pruned_content)
            self.log.append(f"{label}: {tokens} tokens (pruned {chars_removed} chars)")

        self.used += tokens
        return pruned_content

    def remaining(self) -> int:
        return self.AVAILABLE - self.used

    def usage_pct(self) -> float:
        return round(self.used / self.AVAILABLE * 100, 1)

    def report(self) -> str:
        lines = ["── Context Budget ──"]
        lines += self.log
        lines += [f"Total used: {self.used:,} / {self.AVAILABLE:,} ({self.usage_pct()}%)"]
        lines += [f"Remaining:  {self.remaining():,} tokens"]
        lines += [f"Chars pruned: {self.pruned_chars:,}"]
        return "\n".join(lines)

