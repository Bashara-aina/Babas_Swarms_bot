# ── Backend detection for compression ───────────────────────────
_compressor = None
_compressor_backend = None

def get_compressor_backend():
    """Detect available compression backend. Priority: Ollama phi > MiniMax API > None."""
    global _compressor, _compressor_backend

    if _compressor_backend is not None:
        return _compressor_backend

    # Check Ollama for phi model
    try:
        import requests
        r = requests.get("http://localhost:11434/api/tags", timeout=3)
        models = [m["name"] for m in r.json().get("models", [])]
        phi = next((m for m in models if "phi" in m.lower()), None)
        if phi:
            _compressor_backend = f"ollama/{phi}"
            print(f"ℹ️ Compression backend: Ollama/{phi}")
            return _compressor_backend
    except Exception:
        pass

    # Check if MiniMax API key is available
    if os.environ.get("MINIMAX_API_KEY"):
        _compressor_backend = "minimax-api"
        print("ℹ️ Compression backend: MiniMax API")
        return _compressor_backend

    _compressor_backend = "heuristic"
    print("ℹ️ Compression backend: heuristic (no model available)")
    return _compressor_backend

# ── Main compression function ─────────────────────────────────────
def compress(text: str, ratio: float = 0.5, instruction: str = "",
             question: str = "") -> dict:
    """
    Compress text. Uses Ollama phi if available, else MiniMax API, else heuristic.
    ratio = fraction to KEEP (0.5 = keep 50%).
    """
    start = time.time()
    original_tokens = count_tokens(text)

    # Stage 1: prune obvious waste
    pruned, chars_removed = prune_text(text)

    # Stage 2: apply ratio-based compression
    backend = get_compressor_backend()

    if backend.startswith("ollama/"):
        # Ollama phi compression via LLMLingua
        try:
            import requests
            from llmlingua import PromptCompressor

            model_name = backend.replace("ollama/", "")
            compressor = PromptCompressor(
                model_name=f"ollama/{model_name}",
                use_llmlingua2=False,
                device_map="cpu",
                open_api_config={
                    "api_base": "http://localhost:11434/v1",
                    "api_key": "ollama",
                }
            )
            result = compressor.compress_prompt(
                context=[pruned],
                instruction=instruction,
                question=question,
                ratio=(1.0 - ratio),
                rank_method="longllmlingua",
            )
            compressed = result["compressed_prompt"]
            comp_tokens = count_tokens(compressed)
            return {
                "compressed": compressed,
                "original_tokens": original_tokens,
                "compressed_tokens": comp_tokens,
                "savings_pct": round((1 - comp_tokens / max(original_tokens, 1)) * 100, 1),
                "elapsed_ms": round((time.time() - start) * 1000),
                "backend": backend,
            }
        except Exception as e:
            print(f"⚠️ Ollama compression failed: {e}. Trying MiniMax API.")

    if backend in ("minimax-api",) and os.environ.get("MINIMAX_API_KEY"):
        # MiniMax API compression
        try:
            import litellm
            keep_pct = int(ratio * 100)
            compress_prompt = f"""You are a context compressor. Compress to ~{keep_pct}% of length.
RULES:
- Keep all technical facts, code logic, variable names, function signatures
- Remove: filler words, redundant explanations, repeated info, verbose phrasing
- Output ONLY compressed text, no preamble
- Preserve code blocks exactly

{"TASK CONTEXT: " + question if question else ""}

TEXT TO COMPRESS:
{pruned}"""

            response = litellm.completion(
                model="minimax/MiniMax-M2.7",
                api_base="https://api.minimax.chat/v1",
                api_key=os.environ["MINIMAX_API_KEY"],
                messages=[{"role": "user", "content": compress_prompt}],
                max_tokens=max(500, int(original_tokens * ratio)),
                temperature=0.1,
            )
            compressed = response.choices[0].message.content
            comp_tokens = count_tokens(compressed)
            return {
                "compressed": compressed,
                "original_tokens": original_tokens,
                "compressed_tokens": comp_tokens,
                "savings_pct": round((1 - comp_tokens / max(original_tokens, 1)) * 100, 1),
                "elapsed_ms": round((time.time() - start) * 1000),
                "backend": "minimax-api",
            }
        except Exception as e:
            print(f"⚠️ MiniMax API compression failed: {e}. Using heuristic.")

    # Heuristic fallback: keep beginning + end
    words = pruned.split()
    keep_count = int(len(words) * ratio)
    compressed = " ".join(words[:keep_count])
    comp_tokens = count_tokens(compressed)
    return {
        "compressed": compressed,
        "original_tokens": original_tokens,
        "compressed_tokens": comp_tokens,
        "savings_pct": round((1 - comp_tokens / max(original_tokens, 1)) * 100, 1),
        "elapsed_ms": round((time.time() - start) * 1000),
        "backend": "heuristic",
    }

