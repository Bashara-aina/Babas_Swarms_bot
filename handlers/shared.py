def _format_for_telegram_html(text: str) -> str:
    """Lightweight formatter to improve readability in Telegram HTML mode.

    Keeps existing HTML intact while normalizing common markdown patterns
    generated by LLM responses.
    """
    if not text:
        return text

    out = html_mod.unescape(text).replace("\r\n", "\n").replace("\r", "\n")

    # Remove noisy markdown fences / backticks that often look robotic in chat
    out = out.replace("```", "\n")
    out = re.sub(r"`([^`\n]{1,120})`", r"<code>\1</code>", out)

    # Normalize markdown headers to bold lines
    out = re.sub(r"(?m)^\s*#{1,3}\s+(.+?)\s*$", r"<b>\1</b>", out)

    # Normalize markdown bullets into Telegram-friendly bullet glyph
    out = re.sub(r"(?m)^\s*-\s+", "• ", out)
    out = re.sub(r"(?m)^\s*\*\s+", "• ", out)

    # Normalize horizontal separators
    out = re.sub(r"(?m)^\s*---+\s*$", "━━━━━━━━━━━━━━━━━━━━", out)

    # Normalize long blank-line runs
    out = re.sub(r"\n{3,}", "\n\n", out)

    # Fix occasional orphan closing/opening code tags from model output
    out = out.replace("</code>\n</code>", "</code>")
    out = out.replace("<code><code>", "<code>")

    return out.strip()


