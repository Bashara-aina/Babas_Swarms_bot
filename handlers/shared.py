# ── Core: agentic loop handler ────────────────────────────────────────────────
async def _run_agent_loop(msg: Message, task: str) -> None:
    """Run the agentic computer-use loop with live progress updates."""
    if not msg.from_user:
        return

    from_user_id = msg.from_user.id
    thread_id = _user_thread.get(from_user_id)

    with contextlib.suppress(Exception):
        logger.info(
            "[USER_CHAT][mode=agent_loop][chat=%s][user=%s] %s",
            msg.chat.id,
            from_user_id,
            (task[:1200] + ("…" if len(task) > 1200 else "")).replace("\n", "\\n"),
        )

    status_msg = await msg.answer("\U0001f916 on it\u2026")
    step_count = 0

    async def on_progress(step_text: str) -> None:
        nonlocal step_count
        step_count += 1
        try:
            if step_text.startswith("\U0001f4ad"):
                logger.info(
                    "[BOT_THOUGHT][chat=%s][user=%s] %s",
                    msg.chat.id,
                    from_user_id,
                    (step_text[:1200] + ("…" if len(step_text) > 1200 else "")).replace("\n", "\\n"),
                )
            else:
                logger.info(
                    "[BOT_PROGRESS][chat=%s][user=%s][step=%s] %s",
                    msg.chat.id,
                    from_user_id,
                    step_count,
                    (step_text[:1200] + ("…" if len(step_text) > 1200 else "")).replace("\n", "\\n"),
                )
        except Exception:
            pass
        try:
            if step_text.startswith("\U0001f4ad"):
                await msg.answer(
                    f"<i>{html_mod.escape(step_text)}</i>",
                    parse_mode="HTML",
                )
            else:
                await status_msg.edit_text(
                    f"<code>[{step_count}]</code> {html_mod.escape(step_text)}",
                    parse_mode="HTML",
                )
        except Exception:
            pass

    async def on_photo(path: str) -> None:
        try:
            photo_file = FSInputFile(path)
            await msg.answer_photo(
                photo=photo_file,
                caption="\U0001f4f8 current screen",
                reply_markup=screenshot_keyboard(),
            )
            _last_screenshot[from_user_id] = path
        except Exception as e:
            import logging

            logging.getLogger(__name__).error("Failed to send screenshot photo: %s", e)

    typing_task = asyncio.create_task(_keep_typing(msg))

    try:
        response, model_used = await agent_loop(
            task,
            progress_fn=on_progress,
            photo_cb=on_photo,
            thread_id=thread_id,
            user_id=str(msg.from_user.id) if msg.from_user else None,
        )
        await _cancel_task(typing_task)
        with contextlib.suppress(Exception):
            await status_msg.delete()
        await send_chunked(msg, response, model_used=model_used)

    except Exception as e:
        await _cancel_task(typing_task)
        from core.error_humanizer import humanize_error_for_display

        friendly = humanize_error_for_display(e, context="/do agent loop")
        err_short = str(e)[:300]
        hint = friendly
        try:
            await status_msg.edit_text(
                f"{hint}\n\n<code>{err_short}</code>",
                parse_mode="HTML",
            )
        except Exception:
            await msg.answer(
                f"{hint}\n\n<code>{err_short}</code>",
                parse_mode="HTML",
            )


# ── Core: single-turn chat handler ────────────────────────────────────────────
async def _execute_chat(
    msg: Message,
    task: str,
    forced_agent: str | None = None,
    show_thinking: bool = True,
    routing_hint: str | None = None,
) -> None:
    """Single-turn LLM chat with typing indicator and chunked output."""
    # FIX #5: Guard against msg.from_user being None
    if not msg.from_user:
        return

    selected_agent = forced_agent or "general"

    with contextlib.suppress(Exception):
        logger.info(
            "[USER_CHAT][mode=chat][chat=%s][user=%s][agent=%s] %s",
            msg.chat.id,
            msg.from_user.id,
            selected_agent,
            (task[:1200] + ("…" if len(task) > 1200 else "")).replace("\n", "\\n"),
        )

    # Use chat.id as thread_id so conversation history is tracked per-chat
    thread_id = str(msg.chat.id) if msg.chat else str(msg.from_user.id)

    typing_task = asyncio.create_task(_keep_typing(msg))
    try:
        response, model_used = await chat(
            task,
            agent_key=selected_agent,
            show_thinking=show_thinking,
            user_id=str(msg.from_user.id),
            thread_id=thread_id,
            routing_hint=routing_hint,
        )
        await _cancel_task(typing_task)
        await send_chunked(msg, response, model_used=model_used)
    except Exception as e:
        await _cancel_task(typing_task)
        from core.error_humanizer import humanize_error_for_display

        friendly = humanize_error_for_display(e, context="chat")
        err_short = str(e)[:300]
        hint = friendly
        await msg.answer(
            f"{hint}: <code>{err_short}</code>",
            parse_mode="HTML",
        )
