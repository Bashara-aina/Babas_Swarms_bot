# ── Helper: send chunked messages ─────────────────────────────────────────────
async def send_chunked(msg: Message, text: str, model_used: str = "") -> None:
    if not text:
        return
    text = _format_for_telegram_html(text)
    with contextlib.suppress(Exception):
        logger.info(
            "[BOT_RESPONSE][chat=%s][model=%s] %s",
            msg.chat.id if msg.chat else None,
            model_used or "unknown",
            (text[:1200] + ("…" if len(text) > 1200 else "")).replace("\n", "\\n"),
        )
    chunks = chunk_output(text, max_length=4000)
    for i, chunk in enumerate(chunks):
        is_last = i == len(chunks) - 1
        markup = result_keyboard(model_used) if (is_last and model_used) else None
        try:
            await msg.answer(chunk, parse_mode="HTML", reply_markup=markup)
        except Exception:
            try:
                safe = html_mod.escape(chunk)
                await msg.answer(safe, parse_mode="HTML", reply_markup=markup)
            except Exception:
                await msg.answer(chunk, reply_markup=markup)
        if not is_last:
            await asyncio.sleep(0.3)


# ── Helper: typing indicator ──────────────────────────────────────────────────
async def _keep_typing(msg: Message) -> None:
    """Send typing indicator every 4s until cancelled. Stops on persistent errors."""
    consecutive_errors = 0
    while True:
        try:
            if msg.bot is not None:
                await msg.bot.send_chat_action(msg.chat.id, "typing")
            consecutive_errors = 0
        except Exception as e:
            consecutive_errors += 1
            if consecutive_errors >= 3:
                logger.debug("keep_typing stopped after %d errors: %s", consecutive_errors, e)
                break
        await asyncio.sleep(4)


async def _cancel_task(task: asyncio.Task | None) -> None:
    if task is None:
        return
    task.cancel()
    try:
        await task
    except asyncio.CancelledError:
        pass
    except Exception as e:
        logger.debug("Task cancelled with error: %s", e)


